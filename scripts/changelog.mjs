/**
 * Build CHANGELOG.md from the release notes published on GitHub, newest first, so the file and
 * the releases page stay one text. It needs the GitHub CLI, signed in to the repository.
 *
 * Run: `node scripts/changelog.mjs [--repo owner/name] [--out CHANGELOG.md]`
 *
 * Before a release is published, `--next vX.Y.Z --notes <file> [--date YYYY-MM-DD]` adds the
 * notes of that version, so the file that ships with the release already lists it.
 *
 * The Changelog page of the settings reads data/changelog.json, which is not kept in Git:
 * `--from CHANGELOG.md [--data data/changelog.json]` writes it from that file, with no network.
 * The dev server, the build and the checks run it first.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { pathToFileURL } from "node:url";

const DEFAULT_REPO = "zenetys/hyoai";

/**
 * Order two release tags, the newest version first.
 *
 * @param a - Tag such as "v1.4.2"
 * @param b - Tag such as "v1.10.0"
 * @returns A negative number when a comes first
 */
export function compareTags(a, b) {
    const parts = (tag) => tag.replace(/^v/, "").split(".").map(Number);
    const [left, right] = [parts(a), parts(b)];
    for (let i = 0; i < Math.max(left.length, right.length); i++) {
        const diff = (right[i] ?? 0) - (left[i] ?? 0);
        if (diff !== 0) return diff;
    }
    return 0;
}

/**
 * Turn the body of a release into text for the changelog: the screenshots are left out, as the
 * releases page shows them, and the headings move one level down under the version heading.
 *
 * @param body - Markdown body of the release
 * @returns The cleaned Markdown, without surrounding blank lines
 */
export function cleanNotes(body) {
    const withoutPictures = body
        .replace(/\r\n/g, "\n")
        .replace(/<picture>[\s\S]*?<\/picture>/g, "")
        .replace(/^!\[[^\]]*\]\([^)]*\)[ \t]*$/gm, "");
    let fenced = false;
    const lines = withoutPictures.split("\n").map((line) => {
        if (/^\s*```/.test(line)) fenced = !fenced;
        if (fenced) return line;
        return line.replace(/^(#{1,5}) /, "$1# ");
    });
    return lines
        .join("\n")
        .replace(/\n{3,}/g, "\n\n")
        .trim();
}

/**
 * Write the whole changelog.
 *
 * @param entries - Releases to list, each with its tag, its date and the body of its notes
 * @param repo - Repository as "owner/name", for the links
 * @returns The Markdown of CHANGELOG.md
 */
export function renderChangelog(entries, repo) {
    const home = `https://github.com/${repo}`;
    const header = [
        "# Changelog",
        "",
        `The release notes of every version, newest first: the same text as the [releases page](${home}/releases), without its screenshots.`,
        "",
        "This file is generated by `node scripts/changelog.mjs`: edit the release notes, not this file.",
    ].join("\n");
    const sections = [...entries]
        .sort((a, b) => compareTags(a.tag, b.tag))
        .map((entry) => {
            const version = entry.tag.replace(/^v/, "");
            const title = `## [${version}](${home}/releases/tag/${entry.tag}) - ${entry.date}`;
            return `${title}\n\n${cleanNotes(entry.body)}`;
        });
    return `${[header, ...sections].join("\n\n")}\n`;
}

/**
 * Read the versions of a CHANGELOG.md written by renderChangelog.
 *
 * @param markdown - The text of the file
 * @returns One entry per version, in the order of the file: its number, its date and its notes
 */
export function parseChangelog(markdown) {
    const heading = /^## \[(\d+\.\d+\.\d+)\]\([^)]*\) - (\d{4}-\d{2}-\d{2})$/;
    const entries = [];
    let fenced = false;
    for (const line of markdown.replace(/\r\n/g, "\n").split("\n")) {
        if (/^\s*```/.test(line)) fenced = !fenced;
        const match = fenced ? null : heading.exec(line);
        if (match) entries.push({ version: match[1], date: match[2], lines: [] });
        else entries.at(-1)?.lines.push(line);
    }
    return entries.map(({ version, date, lines }) => ({
        version,
        date,
        notes: lines.join("\n").trim(),
    }));
}

/**
 * Write the entries as the data file of the application.
 *
 * @param entries - Versions with their number, their date and their notes
 * @returns The JSON of data/changelog.json
 */
export function renderData(entries) {
    return `${JSON.stringify(entries, null, 4)}\n`;
}

/**
 * Run the GitHub CLI and parse its JSON answer.
 *
 * @param args - Arguments passed to `gh`
 * @returns The parsed JSON output
 */
const gh = (args) => JSON.parse(execFileSync("gh", args, { encoding: "utf8" }));

/**
 * Read the published releases of a repository.
 *
 * @param repo - Repository as "owner/name"
 * @returns One entry per release that is not a draft
 */
export function fetchReleases(repo) {
    const list = gh([
        "release",
        "list",
        "-R",
        repo,
        "--limit",
        "200",
        "--json",
        "tagName,publishedAt,isDraft",
    ]);
    return list
        .filter((release) => !release.isDraft)
        .map((release) => {
            const { body } = gh(["release", "view", release.tagName, "-R", repo, "--json", "body"]);
            return { tag: release.tagName, date: release.publishedAt.slice(0, 10), body };
        });
}

/**
 * Read the options of the command line.
 *
 * @param argv - The arguments after the script name
 * @returns The options by name, without their leading dashes
 */
export function parseArgs(argv) {
    const options = {};
    for (let i = 0; i < argv.length; i += 2) options[argv[i].replace(/^--/, "")] = argv[i + 1];
    return options;
}

/**
 * Generate the files.
 *
 * @param argv - The arguments after the script name
 */
function main(argv) {
    const options = parseArgs(argv);
    const repo = options.repo ?? DEFAULT_REPO;
    if (options.from) {
        const dataFile = options.data ?? "data/changelog.json";
        const list = parseChangelog(readFileSync(options.from, "utf8"));
        mkdirSync(dirname(dataFile), { recursive: true });
        writeFileSync(dataFile, renderData(list));
        console.log(`${list.length} versions written to ${dataFile}`);
        return;
    }

    const entries = fetchReleases(repo).filter((entry) => entry.tag !== options.next);

    if (options.next) {
        if (!options.notes) throw new Error("--next needs --notes <file>");
        const date = options.date ?? new Date().toISOString().slice(0, 10);
        entries.push({ tag: options.next, date, body: readFileSync(options.notes, "utf8") });
    }

    writeFileSync(options.out ?? "CHANGELOG.md", renderChangelog(entries, repo));
    console.log(`${entries.length} releases written`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    main(process.argv.slice(2));
}
