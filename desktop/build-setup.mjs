/**
 * Build the ZALEANAI setup exe: embeds dist/ZALEANAI.exe and compiles
 * desktop/setup/Setup.cs. Run after build-exe.mjs.
 */
import { execFile } from "node:child_process";
import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);
const ROOT = resolve(fileURLToPath(new URL("../", import.meta.url)));
const DIST_DIR = join(ROOT, "dist");
const APP_EXE = join(DIST_DIR, "ZALEANAI.exe");
const SETUP_DIR = join(ROOT, "desktop", "setup");
const SETUP_CS = join(SETUP_DIR, "Setup.cs");
const BUILD_INFO = join(SETUP_DIR, "BuildInfo.g.cs");
const ICON = join(ROOT, "desktop", "icon.ico");
const OUT_DIR = join(DIST_DIR, "安装");
const OUT = join(OUT_DIR, "ZALEANAI安装程序.exe");
const CSC =
    process.env.CSC ||
    join(
        process.env.WINDIR ?? "C:\\Windows",
        "Microsoft.NET",
        "Framework64",
        "v4.0.30319",
        "csc.exe",
    );

async function exists(path) {
    try {
        await stat(path);
        return true;
    } catch {
        return false;
    }
}

for (const [path, hint] of [
    [CSC, "找不到 C# 编译器，用环境变量 CSC 指定 csc.exe 的完整路径"],
    [APP_EXE, "找不到 dist/ZALEANAI.exe，先运行 node desktop/build-exe.mjs"],
    [SETUP_CS, "找不到 desktop/setup/Setup.cs"],
    [ICON, "找不到 desktop/icon.ico"],
]) {
    if (!(await exists(path))) {
        console.error(hint);
        console.error(path);
        process.exit(1);
    }
}

const pkg = JSON.parse(await readFile(join(ROOT, "package.json"), "utf8"));
const version = String(pkg.version || "1.0.0");

await writeFile(
    BUILD_INFO,
    "// Generated by desktop/build-setup.mjs; do not edit.\n" +
        "namespace ZaleanaiSetup\n" +
        "{\n" +
        "    internal static class BuildInfo\n" +
        "    {\n" +
        `        public const string Version = "${version.replace(/"/g, "")}";\n` +
        "    }\n" +
        "}\n",
    "utf8",
);

const args = [
    "-nologo",
    "-target:winexe",
    "-optimize+",
    "-codepage:65001",
    `-out:${OUT}`,
    `-win32icon:${ICON}`,
    "-r:System.dll",
    "-r:System.Drawing.dll",
    "-r:System.Windows.Forms.dll",
    `-resource:${ICON},meta/icon.ico`,
    `-resource:${APP_EXE},payload/ZALEANAI.exe`,
    SETUP_CS,
    BUILD_INFO,
];

await mkdir(OUT_DIR, { recursive: true });
try {
    await rm(OUT);
} catch {
    // First build.
}

console.log(`打包安装程序（内嵌 ZALEANAI.exe，版本 ${version}）→ ${OUT}`);

try {
    await run(CSC, args, { maxBuffer: 20 * 1024 * 1024 });
} catch (error) {
    console.error("编译失败：");
    console.error(error.stdout || "");
    console.error(error.stderr || error.message);
    process.exit(1);
}

const info = await stat(OUT);
console.log(`完成：${OUT}`);
console.log(`安装程序 ${(info.size / 1024).toFixed(0)} KB，双击即可安装。`);
